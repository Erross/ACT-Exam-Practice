export function applyScienceTellRepairs(sets){
  return sets.map(set=>({
    ...set,
    questions:set.questions.map(question=>{
      const repairs=SCIENCE_TELL_REPAIRS[question.id];
      if(!repairs) return question;
      const choices=[...question.choices];
      for(const [letter,text] of Object.entries(repairs)){
        const index="ABCD".indexOf(letter);
        if(index<0 || letter===question.correct) throw new Error(`Invalid Science tell repair for ${question.id} ${letter}`);
        choices[index]=text;
      }
      return {...question,choices};
    }),
  }));
}
